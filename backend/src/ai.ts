import OpenAI from 'openai'

const apiKey = process.env.OPENAI_API_KEY
const client = apiKey ? new OpenAI({ apiKey }) : null

const LANG_NAMES: Record<string, string> = {
  ru: 'русский',
  kk: 'казахский',
  en: 'английский',
}

export async function generateQuestions(
  transcript: string,
  language: 'ru' | 'kk' | 'en',
): Promise<string[]> {
  if (!client) {
    console.error('[AI] OPENAI_API_KEY not set')
    return []
  }
  const langName = LANG_NAMES[language]
  try {
    const completion = await client.chat.completions.create({
      model: 'gpt-4o-mini',
      temperature: 0.7,
      max_tokens: 300,
      response_format: { type: 'json_object' },
      messages: [
        {
          role: 'system',
          content: `Ты — ассистент глухого или слабослышащего студента в учебном классе. Преподаватель ведёт урок на разные темы: математика, программирование, физика, химия, биология, география, история, литература, базы данных, информатика, экономика и др. Студент усвоил базу и хочет задать ВДУМЧИВЫЙ вопрос для углубления знаний.

Тебе передан транскрипт последних 30-60 секунд речи преподавателя. Сгенерируй 4-5 СОДЕРЖАТЕЛЬНЫХ ВОПРОСОВ среднего уровня сложности, которые покажут что студент думает над материалом.

ХОРОШИЕ вопросы (примеры по разным предметам):
- "Как изменится результат если входные данные нечисловые?"
- "В каких случаях этот метод не работает?"
- "Какой механизм лежит в основе этого процесса?"
- "Чем этот подход лучше альтернативного?"
- "Что произойдёт при граничных значениях?"
- "Какие исторические причины привели к этому событию?"
- "Какая связь между этим понятием и тем что мы изучали раньше?"
- "Можно ли применить этот принцип в другой области?"
- "Какие ограничения у этого метода?"
- "Что произойдёт если изменить одну переменную?"

ПЛОХИЕ вопросы (НЕ генерировать):
- Слишком элементарные ("Что такое X?", "Повторите Y", "Как пишется Z?")
- Просьбы решить задачу или дать готовый код/формулу
- Философские расширения вне предмета ("Как это влияет на общество?")
- Вопросы требующие 10+ минут ответа

ПРАВИЛА:
1. Каждый вопрос — 6-15 слов, конкретный и осмысленный
2. Опирайся на КОНКРЕТНЫЕ термины/концепции из транскрипта
3. Формулировки: "как", "почему", "что произойдёт если", "в каких случаях", "чем отличается", "какая связь"
4. Запрещено выдавать готовые ответы — только вопросы для размышления
5. Если транскрипт пустой/короткий — общие вопросы типа "Какая практическая ценность темы?", "Где это применяется?"

Язык вопросов: ${langName}.

Отвечай строго в JSON: {"questions": ["вопрос1", "вопрос2", "вопрос3", "вопрос4", "вопрос5"]}`,
        },
        {
          role: 'user',
          content: transcript.slice(0, 2000) || '(транскрипт пуст)',
        },
      ],
    })
    const parsed = JSON.parse(
      completion.choices[0]?.message?.content ?? '{}',
    ) as { questions?: unknown }
    if (!Array.isArray(parsed.questions)) return []
    return parsed.questions
      .filter((q): q is string => typeof q === 'string')
      .slice(0, 5)
  } catch (err) {
    console.error(
      `[AI] generateQuestions failed: ${err instanceof Error ? err.message : String(err)}`,
    )
    return []
  }
}
